# -*- coding: utf-8 -*-
"""
高中數學運算
=====================================================================
本檔案涵蓋高中階段常見的數學運算，並以 Python 程式碼示範，
每一段都會先說明數學原理，再提供程式範例與執行結果。

內容總覽：
  1. 角度與弧度轉換
  2. 三角函數（sin、cos、tan）
  3. 對數（log）
  4. 指數與指數函數（exp）
  5. 等差數列與等比數列
  6. 排列與組合
  7. 二次方程式求解
  8. 向量運算
  9. 統計：平均數、中位數、標準差
"""

import math          # 提供 sqrt、sin、cos、log、pi 等數學函式
import statistics    # 提供平均數、中位數、標準差等統計函式

print("=" * 70)
print("1. 角度與弧度轉換")
print("=" * 70)
# ---------------------------------------------------------------------
# 說明：三角函數常使用兩種角度單位。
#   一圈 = 360 度 = 2π 弧度（約 6.2832）
#   弧度 = 角度 × π / 180
#   角度 = 弧度 × 180 / π
# ---------------------------------------------------------------------
degrees = 90
radians = math.radians(degrees)          # 角度 → 弧度
degrees_back = math.degrees(radians)     # 弧度 → 角度
print(f"{degrees} 度 = {radians:.4f} 弧度")
print(f"{radians:.4f} 弧度 = {degrees_back} 度")

print()
print("=" * 70)
print("2. 三角函數（sin、cos、tan）")
print("=" * 70)
# ---------------------------------------------------------------------
# 說明：三角函數描述直角三角形邊長的比值，也描述圓周上的座標。
#   sin θ = 對邊 / 斜邊
#   cos θ = 鄰邊 / 斜邊
#   tan θ = 對邊 / 鄰邊
# 注意：Python 的 sin/cos/tan 參數必須是「弧度」。
# ---------------------------------------------------------------------
theta_deg = 30
theta = math.radians(theta_deg)
print(f"θ = {theta_deg} 度")
print(f"  sin θ = {math.sin(theta):.4f}")
print(f"  cos θ = {math.cos(theta):.4f}")
print(f"  tan θ = {math.tan(theta):.4f}")
print(f"  驗證：sin²θ + cos²θ = {math.sin(theta)**2 + math.cos(theta)**2:.4f} ≈ 1")

print()
print("=" * 70)
print("3. 對數（log）")
print("=" * 70)
# ---------------------------------------------------------------------
# 說明：對數是次方的相反運算。
#   若 aᵇ = N，則 b = log_a(N)（以 a 為底 N 的對數）。
#   math.log(x)       → 以自然對數 e 為底
#   math.log(x, 底)   → 自訂底數
#   math.log10(x)     → 以 10 為底
# ---------------------------------------------------------------------
x = 100
print(f"log₁₀({x}) = {math.log10(x)}   （因為 10² = {x}）")
print(f"log_e(1)  = {math.log(1)}      （因為 e⁰ = 1）")
print(f"log₂(8)   = {math.log(8, 2)}   （因為 2³ = 8）")

print()
print("=" * 70)
print("4. 指數與指數函數（exp）")
print("=" * 70)
# ---------------------------------------------------------------------
# 說明：指數函數 y = aˣ，常用自然指數 eˣ（e ≈ 2.71828）。
#   指數成長常見於細菌繁殖、複利等模型。
# ---------------------------------------------------------------------
x = 2
print(f"e^{x} = {math.exp(x):.4f}  （e ≈ 2.71828）")
print(f"2^{x} = {2 ** x}")

# 複利範例：本金 10000 元，年利率 5%，存 3 年
principal, rate, years = 10000, 0.05, 3
amount = principal * (1 + rate) ** years
print(f"本金 {principal} 元、年利率 5%、{years} 年後本利和 = {amount:.0f} 元")

print()
print("=" * 70)
print("5. 等差數列與等比數列")
print("=" * 70)
# ---------------------------------------------------------------------
# 說明：
#   等差數列：每一項相差固定公差 d。第 n 項 = a₁ + (n-1)d
#   等比數列：每一項乘以固定公比 r。第 n 項 = a₁ × r^(n-1)
# ---------------------------------------------------------------------
a1, d, n = 3, 4, 10
an = a1 + (n - 1) * d
print(f"等差數列：首項 {a1}、公差 {d}，第 {n} 項 = {a1} + ({n}-1)×{d} = {an}")

g1, r, n2 = 2, 3, 6
gn = g1 * r ** (n2 - 1)
print(f"等比數列：首項 {g1}、公比 {r}，第 {n2} 項 = {g1} × {r}^{n2-1} = {gn}")

print()
print("=" * 70)
print("6. 排列與組合")
print("=" * 70)
# ---------------------------------------------------------------------
# 說明：
#   排列 P(n, k)：從 n 個相異物取 k 個「排成一列」的方法數。
#     P(5, 3) = 5×4×3 = 60（順序有差）
#   組合 C(n, k)：從 n 個相異物取 k 個「湊成一組」的方法數。
#     C(5, 3) = P(5,3) / 3! = 10（順序無差）
#   math.comb / math.perm 為 Python 3.8+ 內建函式。
# ---------------------------------------------------------------------
n, k = 5, 3
print(f"P({n}, {k}) = {math.perm(n, k)}  （排列，順序有差）")
print(f"C({n}, {k}) = {math.comb(n, k)}  （組合，順序無差）")

print()
print("=" * 70)
print("7. 二次方程式求解（ax² + bx + c = 0）")
print("=" * 70)
# ---------------------------------------------------------------------
# 說明：判別式 D = b² - 4ac 決定根的形式。
#   D > 0 ：兩個相異實根
#   D = 0 ：兩個相同實根（重根）
#   D < 0 ：沒有實數根（有共軛虛根）
#   公式解：x = (-b ± √D) / (2a)
# ---------------------------------------------------------------------
def solve_quadratic(a: float, b: float, c: float):
    """解二次方程式 ax² + bx + c = 0，回傳實根列表。"""
    d = b ** 2 - 4 * a * c
    if d < 0:
        return []
    if d == 0:
        return [-b / (2 * a)]
    root = math.sqrt(d)
    return [(-b + root) / (2 * a), (-b - root) / (2 * a)]

roots = solve_quadratic(1, -3, 2)     # x² - 3x + 2 = 0
print(f"解 x² - 3x + 2 = 0：x = {roots}")

roots = solve_quadratic(1, 2, 1)      # x² + 2x + 1 = 0（重根）
print(f"解 x² + 2x + 1 = 0：x = {roots}")

roots = solve_quadratic(1, 0, 1)      # x² + 1 = 0（無實根）
print(f"解 x² + 1 = 0：x = {roots}（無實數根）")

print()
print("=" * 70)
print("8. 向量運算")
print("=" * 70)
# ---------------------------------------------------------------------
# 說明：向量是有大小與方向的量，常寫成 (x, y)。
#   向量加法：逐分量相加        (x₁,y₁) + (x₂,y₂) = (x₁+x₂, y₁+y₂)
#   內積（點積）：x₁·x₂ + y₁·y₂，結果是「純量」
#   向量長度：√(x² + y²)
# ---------------------------------------------------------------------
u = (3, 4)
v = (1, 2)

v_sum = (u[0] + v[0], u[1] + v[1])
dot = u[0] * v[0] + u[1] * v[1]
length_u = math.sqrt(u[0] ** 2 + u[1] ** 2)

print(f"向量 u = {u}，v = {v}")
print(f"  u + v = {v_sum}")
print(f"  u · v = {dot}（內積）")
print(f"  |u| = √(3² + 4²) = {length_u}（u 的長度）")

print()
print("=" * 70)
print("9. 統計：平均數、中位數、標準差")
print("=" * 70)
# ---------------------------------------------------------------------
# 說明：
#   平均數：全部資料的總和 ÷ 資料個數
#   中位數：將資料由小到大排列後正中間的值
#   標準差：衡量資料的分散程度，越小代表越集中
# ---------------------------------------------------------------------
data = [62, 71, 68, 84, 90, 75, 77]
mean = statistics.mean(data)
median = statistics.median(data)
stdev = statistics.stdev(data)

print(f"資料：{data}")
print(f"  平均數 = {mean:.2f}")
print(f"  中位數 = {median}")
print(f"  標準差 = {stdev:.2f}")
